def get_target_segments(ad_account_id: int) -> list:
    """
    해당 계정의 핵심 타겟층 목록을 반환합니다.
    지정되지 않은 계정이면 빈 리스트를 반환합니다 (호출부에서 방어 처리 필요).
    """
    return TARGET_SEGMENTS.get(ad_account_id, [])


